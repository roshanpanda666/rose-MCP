"""Push notifications to the user's phone via ntfy (https://ntfy.sh, free; or a self-hosted server).

The topic name is a long random secret generated by `rose push setup`; the phone subscribes to it in
the ntfy app. Messages are short alerts (titles, an approval link), never file or email contents:
anything sent to a public ntfy server should be treated as readable by whoever knows the topic.
"""

from __future__ import annotations

import secrets
import threading

from rose.common import _log, notify_desktop
from rose.config import load_config, update_settings


def settings() -> tuple[str, str]:
    """(ntfy server, topic) from config."""
    cfg = load_config()
    return cfg.get("ntfy_server", "https://ntfy.sh").rstrip("/"), cfg.get("ntfy_topic", "")


def push(title: str, message: str = "", url: str | None = None, priority: str = "default",
         tags: str = "", desktop: bool = True) -> bool:
    """Send a phone push (if set up) and a desktop notification. Never raises; returns True if pushed."""
    if desktop:
        notify_desktop(title, message)
    server, topic = settings()
    if not topic or not load_config().get("push_enabled", True):
        return False

    def send():
        import httpx
        # JSON publishing (not headers): headers must be ASCII, so emoji/accents in titles broke pushes.
        body = {"topic": topic, "title": title[:200], "message": (message or title)[:1000],
                "priority": {"min": 1, "low": 2, "default": 3, "high": 4, "urgent": 5}.get(priority, 3)}
        if tags:
            body["tags"] = [t.strip() for t in tags.split(",") if t.strip()]
        if url:
            body["click"] = url
            body["actions"] = [{"action": "view", "label": "Open", "url": url, "clear": True}]
        try:
            r = httpx.post(server, json=body, timeout=10)
            _log({"event": "push_sent" if r.status_code < 300 else "push_failed", "title": title[:80],
                  "status": r.status_code})
        except Exception as e:
            _log({"event": "push_failed", "title": title[:80], "error": f"{type(e).__name__}: {e}"})

    threading.Thread(target=send, daemon=True).start()
    return True


def push_status() -> dict:
    """Phone push status and how to subscribe."""
    server, topic = settings()
    if not topic:
        return {"enabled": False, "how": "Run `rose push setup` on the laptop, then subscribe in the ntfy app."}
    return {"enabled": bool(load_config().get("push_enabled", True)), "server": server,
            "subscribe": "Open the ntfy app → + → paste the topic shown by `rose push status` on the laptop"}


def cli(argv: list[str]) -> int:
    cmd = argv[0] if argv else "status"
    server, topic = settings()
    if cmd == "setup":
        if not topic:
            topic = "rose-" + secrets.token_urlsafe(18).replace("_", "x").replace("-", "y")
            update_settings({"ntfy_topic": topic, "push_enabled": True})
        print("1. Install the ntfy app on your phone (Play Store / App Store / F-Droid).")
        print(f"2. In the app tap + and subscribe to this topic (server {server}):\n\n   {topic}\n")
        print("   Keep it secret: anyone with the name can read ROSE's alerts.")
        print("3. Test it with: rose push test")
    elif cmd == "test":
        if not topic:
            print("Not set up. Run: rose push setup")
            return 1
        push("ROSE test", "If you see this on your phone, push works.", tags="white_check_mark")
        import time
        time.sleep(3)
        print("Sent. Check your phone.")
    elif cmd == "off":
        update_settings({"push_enabled": False})
        print("Phone push off (desktop notifications continue). Turn on again: rose push setup")
    else:
        print(f"Server: {server}\nTopic:  {topic or 'not set up (rose push setup)'}\n"
              f"Enabled: {load_config().get('push_enabled', True) and bool(topic)}")
    return 0
